def rank(x):
    s=sorted(range(len(x)), key=lambda i:x[i]); r=[0]*len(x); i=0
    while i<len(x):
        j=i
        while j+1<len(x) and x[s[j+1]]==x[s[i]]: j+=1
        avg=(i+j)/2+1
        for k in range(i,j+1): r[s[k]]=avg
        i=j+1
    return r
def pear(a,b):
    n=len(a); ma=st.mean(a); mb=st.mean(b)
    num=sum((a[i]-ma)*(b[i]-mb) for i in range(n))
    return num/math.sqrt(sum((x-ma)**2 for x in a)*sum((y-mb)**2 for y in b))
def sp(a,b): return pear(rank(a),rank(b))
def partial(rxy,rxz,ryz): return (rxy-rxz*ryz)/math.sqrt((1-rxz**2)*(1-ryz**2))

