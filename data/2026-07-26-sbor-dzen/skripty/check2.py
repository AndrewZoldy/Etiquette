def rank(x):
    s=sorted(range(len(x)), key=lambda i:x[i]); r=[0]*len(x); i=0
    while i<len(x):
        j=i
        while j+1<len(x) and x[s[j+1]]==x[s[i]]: j+=1
        for k in range(i,j+1): r[s[k]]=(i+j)/2+1
        i=j+1
    return r
def pear(a,b):
    n=len(a); ma=st.mean(a); mb=st.mean(b)
    return sum((a[i]-ma)*(b[i]-mb) for i in range(n))/math.sqrt(
        sum((x-ma)**2 for x in a)*sum((y-mb)**2 for y in b))
def sp(a,b): return pear(rank(a),rank(b))
def part(rxy,rxz,ryz): return (rxy-rxz*ryz)/math.sqrt((1-rxz**2)*(1-ryz**2))

def cols(rows):
    return ([r[1] for r in rows],[r[4] for r in rows],[r[5] for r in rows],
            [r[6] for r in rows],[r[3] for r in rows],list(range(1,len(rows)+1)))

pk,ctr,dc,w,dz,order=cols(D)

print("=== CTR РЕШАЕТСЯ ДО КЛИКА: ложность корреляции 'слова~CTR' ===")
rwc=sp(w,ctr); rtw=sp(order,w); rtc=sp(order,ctr)
print("слова~CTR rho =",round(rwc,3),"(проходит порог значимости 0.648!) — но объём текста читателю ДО клика не виден")
print("частная слова~CTR | номер выпуска =",round(part(rwc,rtw,rtc),3)," -> корреляция целиком наведённая")

print("\n=== ПЕРВИЧНЫЙ ПОКАЗАТЕЛЬ (дочитывания) — что им управляет ===")
