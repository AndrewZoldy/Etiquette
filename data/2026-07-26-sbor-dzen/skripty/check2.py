print("слова | показы         =",round(part(rwd,rpw,rpd),3))
print("порог значимости df=7  = 0.666  -> ни одна частная не проходит, кроме двух последних на грани")

print("\n=== СКОЛЬКО НАБЛЮДЕНИЙ НУЖНО, ЧТОБЫ РАЗВЕСТИ ДЛИНУ И КАЛЕНДАРЬ ===")
