# -*- coding: utf-8 -*-
import pandas as pd, numpy as np
pd.set_option('display.width', 250)
pd.set_option('display.max_columns', 200)
m = pd.read_pickle('out/full.pkl')

m['half'] = m['date'].dt.year.astype(str) + 'H' + np.where(m['date'].dt.month <= 6, '1', '2')
print("=== half ===")
print(m['half'].value_counts().sort_index())
print("\n=== эпоха ===")
print(m['эпоха'].value_counts())
print("\n=== date range ===", m['date'].min(), m['date'].max())
print("\n=== comments_enabled raw ===")
print(m['comments_enabled'].value_counts(dropna=False))
print("\n=== comments_enabled types ===", set(type(x).__name__ for x in m['comments_enabled']))
print("\n=== ce=False by half ===")
ce = m['comments_enabled']
print(pd.crosstab(m['half'], ce.astype(str), dropna=False))
print("\n=== сцена ===")
print(m['сцена'].value_counts())
print("\n=== функция ===")
print(m['функция'].value_counts())
print("\n=== порог_входа ===")
print(m['порог_входа'].value_counts())
print("\n=== age_days describe ===")
print(m['age_days'].describe())
print("\n=== src ===")
print(m['src'].value_counts(dropna=False))
print("\n=== type/item_type ===")
print(m['type'].value_counts(dropna=False))
print(m['item_type'].value_counts(dropna=False))
print("\n=== cover_tpl (top) ===")
print(m['cover_tpl'].value_counts(dropna=False).head(10))
print("\n=== suites sample ===")
print(m['suites'].astype(str).value_counts(dropna=False).head(10))
print("\n=== dow ===")
print(m['dow'].value_counts())
