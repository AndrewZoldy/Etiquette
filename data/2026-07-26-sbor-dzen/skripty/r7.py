# -*- coding: utf-8 -*-
import pandas as pd, numpy as np
m = pd.read_pickle('out/full.pkl'); m['ce']=(m['comments_enabled']==True)
print("Проверка утверждения критика: когортный ряд Факта 2 на ce=True = 54 720 / 222 407 / 78 398 / 129 989")
for a,b in [(0,60),(150,220),(300,400),(400,550)]:
    s=m[(m['age_days']>=a)&(m['age_days']<b)]; c=s[s['ce']]
    print(f"  {a}-{b}д: ВСЕ n={len(s):3d} shows={s['shows'].median():>9,.0f} reads={s['reads'].median():>7,.0f} | "
          f"ce=True n={len(c):3d} shows={c['shows'].median():>9,.0f} reads={c['reads'].median():>7,.0f}".replace(',',' '))
print("\nМесячные суммы дочитываний В СРЕДНЕМ ЗА МЕСЯЦ по блокам (шкала «б», нормировка на длину блока):")
m['ymS']=m['ym'].astype(str)
g=m.groupby('ymS')['reads'].sum()/1e6
for name,mos in [('май-июл 2025',['2025-05','2025-06','2025-07']),('авг-сен 2025',['2025-08','2025-09']),
                 ('окт-дек 2025',['2025-10','2025-11','2025-12']),('янв-мар 2026',['2026-01','2026-02','2026-03']),
                 ('апр-июл 2026',['2026-04','2026-05','2026-06','2026-07']),
                 ('2024H1',['2024-01','2024-02','2024-03','2024-04','2024-05','2024-06']),
                 ('2024H2',['2024-07','2024-08','2024-09','2024-10','2024-11','2024-12'])]:
    s=g[g.index.isin(mos)]
    print(f"  {name:14s} мес={len(s)} сумма={s.sum():6.3f} млн  в среднем за месяц={s.mean():.3f} млн  медиана мес={s.median():.3f}")
print("\nВклад одной статьи в июль 2026:")
j=m[m['ymS']=='2026-07']
print(f"  всего reads июль 2026 = {j['reads'].sum():,.0f}; максимум одной статьи = {j['reads'].max():,.0f} ({j['reads'].max()/j['reads'].sum():.1%})".replace(',',' '))
print(f"  без топ-1 статьи: {j['reads'].sum()-j['reads'].max():,.0f} = {(j['reads'].sum()-j['reads'].max())/1e6:.3f} млн".replace(',',' '))
print("\nЧисло публикаций статей в месяц (для нормировки шкалы «б»):")
print((m.groupby('ymS').size()).loc['2024-01':].to_string())
