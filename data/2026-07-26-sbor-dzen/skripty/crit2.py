import pandas as pd, numpy as np
pd.set_option('display.width', 250); pd.set_option('display.max_rows', 300)
m = pd.read_pickle('out/full.pkl')
m['half'] = m['date'].dt.year.astype(str) + 'H' + ((m['date'].dt.month > 6).astype(int) + 1).astype(str)
d = m[m['comments_enabled'] == False].sort_values('date')
print('=== ce=False: titles, date, scene, function, shows ===')
print(d[['date','сцена','функция','порог_входа','серийная_рубрика','shows','opens','reads','comments','ctr']].assign(t=d.title_studio.str[:52]).to_string())
print()
print('=== scene mix ce=False vs ce=True in 2025H2+2026H1 ===')
w = m[m['half'].isin(['2025H2','2026H1'])]
print(pd.crosstab(w['сцена'], w['comments_enabled'], normalize='columns').round(3).to_string())
print()
print('=== function mix ===')
print(pd.crosstab(w['функция'], w['comments_enabled'], normalize='columns').round(3).to_string())
print()
print('=== hour of publication ===')
print(w.groupby(w['comments_enabled'].astype(str))['hour'].describe().to_string())
print()
print('=== suites (подборки) ===')
print(w.groupby(w['comments_enabled'].astype(str))['suites'].apply(lambda s: s.astype(str).value_counts().head(5)).to_string())
print()
print('=== text length / structure ===')
print(w.groupby(w['comments_enabled'].astype(str))[['n_words','n_images','n_paragraphs','time_to_read_s','read_rate','min_per_read']].median().to_string())
