# -*- coding: utf-8 -*-
import pandas as pd, numpy as np
pd.set_option('display.width', 250); pd.set_option('display.max_columns', 100); pd.set_option('display.max_rows', 300)
m = pd.read_pickle('out/full.pkl')
m['ce'] = m['comments_enabled']
f = m[m['ce'] == False]
print("n ce=False:", len(f))
print("date range ce=False:", f['date'].min(), "->", f['date'].max())
print()
print("=== ce=False by month ===")
print(f.groupby(f['date'].dt.to_period('M')).size().to_string())
print()
print("=== ce=NaN rows ===")
print(m[m['ce'].isna()][['date','title_studio','shows','opens','reads','type','src']].to_string())
print()
print("=== ce=False: shows describe ===")
print(f['shows'].describe().to_string())
print("median shows", f['shows'].median(), "median reads", f['reads'].median())
print()
print("=== ce=False with comments>0 ===")
print(f[f['comments']>0][['date','_xlrow','oid','title_studio','shows','opens','reads','comments','comments_public','likes','likes_public','views_public']].to_string())
print()
print("=== ce=False top shows ===")
print(f.nlargest(8,'shows')[['date','title_studio','shows','reads','ctr','comments','сцена']].to_string())
print()
print("=== ce=False dow ===")
print(f['dow'].value_counts().to_string())
print()
print("=== ce=False hour ===")
print("median hour ce=False:", f['hour'].median(), " ce=True:", m[m['ce']==True]['hour'].median())
print()
print("=== window 2025-09-16..2026-05-21 ===")
w = m[(m['date']>=pd.Timestamp('2025-09-16')) & (m['date']<=pd.Timestamp('2026-05-21'))]
print("n window:", len(w), " ce=False in window:", (w['ce']==False).sum(), " ce=True:", (w['ce']==True).sum())
print()
print("=== сцена ce=False ===")
print(f['сцена'].value_counts().to_string())
print()
print("=== функция ce=False ===")
print(f['функция'].value_counts().to_string())
print("=== порог ce=False ===")
print(f['порог_входа'].value_counts().to_string())
print()
print("=== reads zeros ===")
print("reads==0 count:", (m['reads']==0).sum(), " shows==0:", (m['shows']==0).sum(), " opens==0:", (m['opens']==0).sum())
