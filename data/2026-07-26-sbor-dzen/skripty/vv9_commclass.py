# -*- coding: utf-8 -*-
import pandas as pd, numpy as np, re
pd.set_option('display.width',300); pd.set_option('display.max_columns',60); pd.set_option('display.max_rows',400)
C = pd.read_pickle('vv_comments.pkl')
C['t']=C.text.fillna('').str.lower()

pat = {
 'A_благодарность':      r'спасибо|благодар|полезн|удобн|информатив|прекрасный обзор|хороший день|отличн(ая|ый)|буду ждать|сохранила',
 'B_язык_стиль':         r'стилист|вычурн|виньетк|пафос|словесн|синоним|повторя|речевые паразит|нового?яз|албанск|перл|эпитет|неспешн|крупнейш|атмосферн|один из|входит и выходит|вода|воды|нудят|занудств|тягомотин|винегрет',
 'C_длина_формат':       r'многа букафф|много букв|простын|краткость|нудят|занудств|тягомотин|долго, нудно|не дочитала|надоело|мне надоело|прочитать обо всем|все в одном месте|всё в одном месте|в одном месте|бюллетен|анонс|дайджест|перечислен',
 'D_просьба':            r'без ссылок|ссылк|пользуйтесь|включайте мозг|краткость|надо возвращать|хотелось бы|прошу|дайте',
 'E_ошибки_факты':       r'воскресный вечер был вчера|глухар|крупнейш|весник|вестник, однако|speaking club|нестыковк|путал|ошибк',
 'F_заголовок_светскость':r'светская жизнь|светск|вестник|аристократ|претенциозн|заголовок|не из светской|тусовоч',
 'G_уместность_война':   r'воины гибнут|воины|на войне|дрон|бпла|нпз|траур|кощунств|зажратых|далеки они от народа|хлеба и зрелищ|гибнут',
 'H_соцфлуд_склока':     r'бот|заблокир|бан|пластилин|протокол|курица|хам|дизлайк|шизу|санитар|смирительн',
 'I_стихи_цитаты':       r'\(с\)|\(c\)|ля ля|кумир, кумир',
 'J_свой_опыт_события':  r'был в|была в|была на|ходил|сходил|планировал|рекомендую|советую|жду |посетил|ресторан|кинотеатр|мясников|комарово|вуокс|выборг',
}
for k,p in pat.items(): C[k]=C.t.str.contains(p,regex=True).astype(int)
print("### КЛАССИФИКАЦИЯ 302 КОММЕНТАРИЕВ К 10 ВЫПУСКАМ (пересечения возможны)")
tot=C[list(pat)].sum().sort_values(ascending=False)
res=pd.DataFrame({'комментариев':tot,'доля_%':(tot/len(C)*100).round(1)})
print(res.to_string())
print("\nвсего комментариев:",len(C), "| root:",(C.level=='root').sum(), "| ответов:",(C.level=='child').sum())

print("\n### ПО ВЫПУСКАМ")
g=C.groupby(['вып','дата']).agg(**{'всего':('text','size'),'root':('level',lambda s:(s=='root').sum()),
   'авторов':('author','nunique')}, **{k:(k,'sum') for k in pat})
print(g.to_string())

print("\n### КОНЦЕНТРАЦИЯ: кто пишет")
a=C.groupby('author').agg(комм=('text','size'),выпусков=('вып','nunique')).sort_values('комм',ascending=False)
print(a.head(15).to_string())
top=a.head(7).index
print(f"\nдоля 7 самых активных: {C.author.isin(top).mean()*100:.1f}% всех комментариев ({C.author.isin(top).sum()} из {len(C)})")
print(f"уникальных авторов всего: {C.author.nunique()}")
print(f"авторов, отметившихся ровно в 1 выпуске: {(a.выпусков==1).sum()} из {len(a)}")

print("\n### ЛАЙКИ: что аудитория одобряет — топ-12 комментариев по лайкам")
tt=C.sort_values('likes',ascending=False).head(12)[['вып','author','likes','dislikes','text']].copy()
tt['text']=tt.text.str.replace(r'\s+',' ',regex=True).str.slice(0,150)
print(tt.to_string(index=False))
print("\nмедиана лайков у комментариев про язык/стиль (B):", C[C.B_язык_стиль==1].likes.median(),
      f"n={int(C.B_язык_стиль.sum())}")
print("медиана лайков у благодарностей (A):", C[C.A_благодарность==1].likes.median(),
      f"n={int(C.A_благодарность.sum())}")
print("медиана лайков у остальных:", C[(C.A_благодарность==0)&(C.B_язык_стиль==0)].likes.median())

print("\n### ЯВНЫЕ ПРОСЬБЫ / ЖАЛОБЫ НА ФОРМАТ — цитаты дословно")
key = C[C.t.str.contains(r'без ссылок|многа букафф|краткость|простын|не дочитала|мне надоело|в одном месте|бюллетен|анонс мероприятий|заголовок|перечислен|это анонс', regex=True)]
for _,r in key.iterrows():
    print(f"— вып.{r.вып} ({r.дата}) {r.author} [+{r.likes}]: {re.sub(r'\\s+',' ',r.text)[:330]}")
